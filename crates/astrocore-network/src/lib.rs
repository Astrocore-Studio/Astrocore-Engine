//! Сетевой слой Astrocore (раздел 15 дизайн-документа).
//!
//! * [`server::GameServer`] — серверно-авторитарное ядро: рукопожатие, ввод,
//!   движение, двери, правки мира, зона интереса. Не зависит от транспорта и
//!   детерминировано — тестируется без сокетов;
//! * [`client::ClientCore`] — клиентское ядро: реплика мира, предсказание и
//!   согласование движения, интерполяция удалённых сущностей;
//! * [`tcp`] — транспорт на TCP (надёжный упорядоченный поток) с кадрированием.
//!
//! Решение о транспорте (ADR-0006): текущая реализация использует TCP, потому что
//! все сообщения протокола требуют надёжной упорядоченной доставки. UDP-каналы для
//! часто меняющегося состояния и интеграция Lightyear — отдельный этап; ядра
//! сервера и клиента от транспорта не зависят.

