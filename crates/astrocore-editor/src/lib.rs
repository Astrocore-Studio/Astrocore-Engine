//! Ядро Astrocore Studio (раздел 19 дизайн-документа).
//!
//! Здесь всё, что не зависит от окна и GPU и поэтому тестируется без интерфейса:
//!
//! * [`session::EditSession`] — правки мира как обратимые транзакции (undo/redo),
//!   оптимистичная блокировка по ревизии, откат при ошибке посреди транзакции;
//! * [`tools`] — инструменты построения: линия стен, комната, автоматические пол и
//!   потолок по замкнутому контуру, лестница с пробивкой перекрытий, копирование и
//!   зеркальное отражение областей, замена материала, размещение префабов;
//! * [`snap`] — привязка курсора к сетке, вершинам, рёбрам и поверхностям;
//! * [`validate`] — валидатор карты (замкнутые комнаты без прохода, лишние проёмы,
//!   лестницы без площадки и т. п.);
//! * [`view`] — режимы просмотра этажей (все / срез / рентген);
//! * [`project`] — сохранение и загрузка проекта;
//! * [`playtest`] — запуск настоящего игрового сервера на копии карты («играть отсюда»).
//!
//! Графический интерфейс (окно, панели, гизмо) — отдельная оболочка поверх этих
//! API: плагины и инструменты работают только через команды мира.

