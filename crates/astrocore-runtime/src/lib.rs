//! Серверная среда выполнения, не зависящая от Bevy и конкретных игр.
//!
//! * [`doors`] — двери как runtime-состояние над проёмами мира и команда взаимодействия;
//! * [`streaming`] — состояния чанков и уровни активности (active / reduced / dormant);
//! * [`modules`] — API игровых модулей: универсальные события и узлы расширения;
//! * [`sim`] — инфраструктура подключаемых симуляций: граф соединений и расписание модулей.
//!
//! Правила игр (правила и сеттинг конкретной игры) сюда не входят —
//! они подключаются как [`modules::GameModule`].

pub mod doors;
pub mod modules;
pub mod sim;
pub mod streaming;
